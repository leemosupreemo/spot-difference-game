def is_distinct(diff1, diff2, min_dist=8.0):
    """Ensure two differences do not overlap in coordinates."""
    dx = diff1["x"] - diff2["x"]
    dy = diff1["y"] - diff2["y"]
    return (dx*dx + dy*dy) ** 0.5 >= min_dist

def try_op(base_id, title, img_path, op, var_index, existing_diffs, hue_shift=65.0):
    pol = GenerationPolicy(
        name=f"policy_{op}",
        allowed_operations=(op,),
        allow_operation_fallback=False,
        max_candidates_per_operation=24,
        selection_mode="first_pass",
        refine_structural_masks=True if op != "recolor" else False,
    )
    v_id = f"{base_id}_var{var_index}"
    spec = {
        "id": v_id,
        "title": f"{title} ({op.capitalize()})",
        "image_path": img_path,
        "preferred_op": op,
        "difficulty": "Medium",
        "hue_direction_deg": hue_shift,
    }
    
    success, res, log = generate_single_scene_difference(
        spec,
        output_dir=str(OUT_DIR),
        difficulty="Medium",
        policy=pol
    )
    
    if success and res and res.get("diffs"):
        diff = res["diffs"][0]
        # Check distinctness
        for ed in existing_diffs:
            if not is_distinct(diff, ed):
                return None
        # Clean up unwanted duplicate base file generated by pipeline
        dup_base = OUT_DIR / f"{v_id}_base.jpg"
        if dup_base.exists():
            dup_base.unlink()
        return res
    return None

def fallback_duplicate(base_id, title, img_path, var_index, existing_diffs):
    img = cv2.imread(img_path)
    h, w = img.shape[:2]
    qa = SceneAffordanceRouter.evaluate_and_route_canvas(img_path)
    targets = select_segmented_targets(qa["raw_masks"], img.shape)

    for t in targets:
        x1, y1, x2, y2 = t["bbox"]
        pw, ph = x2 - x1, y2 - y1
        regions = find_paste_regions(img, targets, (ph, pw))
        for r in regions:
            var, dest_mask = duplicate_target(img, t, r["center"])
            valid, _, _ = validate_duplicate(img, t, dest_mask)
            if valid:
                ys, xs = np.where(dest_mask > 0)
                bx1, by1, bx2, by2 = int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())
                passed, _, _, _ = PerceptualVerificationEngine.evaluate_display_resolution_and_direct_look(
                    img, var, [bx1, by1, bx2, by2], operation="add", difficulty="Medium"
                )
                if passed:
                    cx_pct = round(float(bx1 + bx2) / 2.0 / float(w) * 100.0, 1)
                    cy_pct = round(float(by1 + by2) / 2.0 / float(h) * 100.0, 1)
                    diff = {
                        "id": 1,
                        "x": cx_pct,
                        "y": cy_pct,
                        "radius": round(max(4.5, min(7.5, max(bx2 - bx1, by2 - by1) / float(w) * 50.0 + 1.2)), 1),
                        "description": "Single added object difference",
                        "hint": "Look closely for an added object",
                        "operation": "add",
                    }
                    if any(not is_distinct(diff, ed) for ed in existing_diffs):
                        continue
                    
                    v_filename = f"{base_id}_var{var_index}_variant.jpg"
                    v_path = str(OUT_DIR / v_filename)
                    Image.fromarray(cv2.cvtColor(var, cv2.COLOR_BGR2RGB)).save(v_path, "JPEG", quality=98)
                    entry = {
                        "id": f"{base_id}_var{var_index}",
                        "title": f"{title} (Added Detail)",
                        "baseImage": img_path,
                        "variantImage": v_path,
                        "operation": "add",
                        "generationMethod": "structural_fallback",
                        "dimensions": {"width": w, "height": h},
                        "aspectRatio": "2:3",
                        "baseId": base_id,
                        "diffs": [diff]
                    }
                    entry["variantCode"] = variant_code(entry)
                    return entry
    return None

def main():
    all_manifest_entries = []
    print("=" * 80)
    print("STARTING 4-VARIANT GENERATION ACROSS 9 SOCIAL BASE CANVASES")
    print("=" * 80)

    for idx, base in enumerate(TARGET_BASES, 1):
        b_id = base["id"]
        title = base["title"]
        b_path = base["path"]
        print(f"\n[{idx}/9] Processing Scene: {b_id} (\"{title}\")")

        existing_diffs = []
        scene_variants = []

        # Desired operations order: add, recolor, remove, reorder
        primary_ops = [
            ("add", 0.0),
            ("recolor", 65.0),
            ("remove", 0.0),
            ("reorder", 0.0),
        ]

        # 1. Try standard operations
        for op, hue_shift in primary_ops:
            var_idx = len(scene_variants) + 1
            if var_idx > 4:
                break
            res = try_op(b_id, title, b_path, op, var_idx, existing_diffs, hue_shift=hue_shift)
            if res and res.get("diffs"):
                diff = res["diffs"][0]
                existing_diffs.append(diff)
                scene_variants.append(res)
                print(f"   ✓ Var {var_idx} [{op.upper()}]: at ({diff['x']}%, {diff['y']}%), r={diff['radius']:.1f}% [{res.get('variantCode', 'OK')}]")

        # 2. If needed, try structural fallback duplicate add
        if len(scene_variants) < 4:
            var_idx = len(scene_variants) + 1
            res_dup = fallback_duplicate(b_id, title, b_path, var_idx, existing_diffs)
            if res_dup and res_dup.get("diffs"):
                diff = res_dup["diffs"][0]
                existing_diffs.append(diff)
                scene_variants.append(res_dup)
                print(f"   ✓ Var {var_idx} [STRUCTURAL DUP]: at ({diff['x']}%, {diff['y']}%), r={diff['radius']:.1f}%")

        # 3. If still needed, generate distinct recolors on other segmented peer items with different hue angles
        extra_hues = [180.0, 110.0, -80.0, 240.0, -120.0]
        hue_idx = 0
        while len(scene_variants) < 4 and hue_idx < len(extra_hues):
            var_idx = len(scene_variants) + 1
            h_shift = extra_hues[hue_idx]
            hue_idx += 1
            res_rec = try_op(b_id, title, b_path, "recolor", var_idx, existing_diffs, hue_shift=h_shift)
            if res_rec and res_rec.get("diffs"):
                diff = res_rec["diffs"][0]
                existing_diffs.append(diff)
                scene_variants.append(res_rec)
                print(f"   ✓ Var {var_idx} [COLOR SHIFT {h_shift}°]: at ({diff['x']}%, {diff['y']}%), r={diff['radius']:.1f}%")

        print(f"   --> Generated {len(scene_variants)} / 4 variants for {b_id}")
        all_manifest_entries.extend(scene_variants)

    # Save Authoritative Manifest
    manifest_path = OUT_DIR / "social_variants_manifest.json"
    with open(manifest_path, "w") as f:
        json.dump(all_manifest_entries, f, indent=2)

    print("\n" + "=" * 80)
    print(f"🎉 COMPLETED: Successfully generated {len(all_manifest_entries)} / {len(TARGET_BASES) * 4} total variants.")
    print(f"📄 Manifest saved to: {manifest_path}")

if __name__ == "__main__":
    main()
